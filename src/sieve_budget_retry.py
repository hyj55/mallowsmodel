def inversion_ball(n, radius):
    """All permutations with <= radius inversions, generated by insertion."""
    rows = [((), 0)]
    for size in range(1, n+1):
        rows = [(p[:size-1-d]+(size-1,)+p[size-1-d:], cost+d)
                for p,cost in rows for d in range(min(size-1,radius-cost)+1)]
    return np.asarray([p for p,_ in rows], dtype=np.int16)


def ball_size(n, radius):
    counts = [1]+[0]*radius
    for size in range(1, n+1):
        counts = [sum(counts[max(0,j-size+1):j+1]) for j in range(radius+1)]
    return sum(counts)


def lex_ranks(orders):
    n = orders.shape[1]
    remaining = np.full(len(orders), (1 << n)-1, dtype=np.uint64)
    rank = np.zeros(len(orders), dtype=np.int64)
    for i in range(n):
        bits = np.left_shift(np.uint64(1),orders[:,i].astype(np.uint64))
        smaller = np.bitwise_count(remaining & (bits-np.uint64(1)))
        rank += smaller.astype(np.int64)*math.factorial(n-i-1)
        remaining ^= bits
    return rank


def lex_unrank(rank, n):
    available=list(range(n)); order=[]
    for size in range(n,0,-1):
        index,rank=divmod(int(rank),math.factorial(size-1))
        order.append(available.pop(index))
    return order


def even_permutation_dp(w,seconds=SECONDS,memory_bytes=MEMORY):
    """Exact first minimum over even permutations: the radius-one greedy sieve."""
    started=time.perf_counter(); n=len(w); estimated=(1<<n)*(128*n+128)
    check_budget(started,estimated,seconds,memory_bytes,m=n,path='even_permutation_dp')
    masks=np.arange(1<<n,dtype=np.int64); labels=np.arange(n)
    membership=(masks[None,:]>>labels[:,None])&1
    sums=np.asarray(w,dtype=np.int64).T@membership
    del membership
    inf=np.iinfo(np.int64).max//8
    f=np.full((1<<n,2),inf,dtype=np.int64); f[0,0]=0
    first=np.full((1<<n,2),-1,dtype=np.int16)
    sizes=np.bitwise_count(masks.astype(np.uint64))
    for size in range(1,n+1):
        selected=masks[sizes==size]; previous=selected[:,None]^(1<<labels)
        valid=(selected[:,None]&(1<<labels))!=0
        parity=np.bitwise_count((previous&((1<<labels)-1)).astype(np.uint64))%2
        for target in (0,1):
            costs=f[previous,parity^target]+sums[labels[None,:],previous]
            costs[~valid]=inf; chosen=costs.argmin(axis=1)
            f[selected,target]=costs[np.arange(len(selected)),chosen]
            first[selected,target]=chosen
        check_budget(started,estimated,seconds,memory_bytes,m=n,path='even_permutation_dp')
    mask=(1<<n)-1; target=0; order=[]
    while mask:
        item=int(first[mask,target]);order.append(item)
        target^=(mask&((1<<item)-1)).bit_count()%2
        mask^=1<<item
    return np.asarray(order),dict(path='even_permutation_dp',engine=ENGINE,
        complete=True,exact=True,objective=int(f[-1,0]),sieve_size=math.factorial(n)//2,
        radius=1,estimated_bytes=estimated,seconds_limit=seconds,memory_bytes=memory_bytes,
        elapsed_seconds=time.perf_counter()-started)


def build_ball_packing(n, radius, seconds=SECONDS, memory_bytes=MEMORY):
    started=time.perf_counter(); count=math.factorial(n)
    # One Boolean per permutation, plus a worst-case packed output buffer.
    # Check the cheap factorial bound before computing a potentially huge ball.
    estimated=count*(1+2*n)
    base=dict(m=n,radius=radius,path='lexicographic_ball_cover',permutations=count)
    check_budget(started,estimated,seconds,memory_bytes,**base)
    ball_count=ball_size(n,radius)
    estimated+=ball_count*(32*n+128)
    check_budget(started,estimated,seconds,memory_bytes,**base)
    if n>20:
        raise ArithmeticError('Memory admission must precede the rank representation limit')
    ball=inversion_ball(n,radius)
    assert len(ball)==ball_count
    active=np.ones(count,dtype=bool)
    kept=np.empty((count,n),dtype=np.int16)
    first=0; size=0
    while first<count:
        if active[first]:
            order=np.asarray(lex_unrank(first,n),dtype=np.int16)
            kept[size]=order; size+=1
            # Relabeling identity's ball by this order gives its Kendall ball.
            active[lex_ranks(order[ball])]=False
            if size%128==0:
                check_budget(started,estimated,seconds,memory_bytes,**base,
                             packing_so_far=size,next_lex_rank=first)
        first+=1
    check_budget(started,estimated,seconds,memory_bytes,**base,packing_so_far=size)
    return kept[:size].copy(),dict(base,engine=ENGINE,complete=True,sieve_size=size,
        ball_size=ball_count,estimated_bytes=estimated,memory_bytes=memory_bytes,
        seconds_limit=seconds,elapsed_seconds=time.perf_counter()-started)


def cached_ball_packing(n,radius,cache=CACHE,seconds=SECONDS,memory_bytes=MEMORY):
    cache=Path(cache);cache.mkdir(parents=True,exist_ok=True)
    stem=f'{ENGINE}-{n}-{radius}-{memory_bytes}-{seconds:g}'
    receipt=cache/(stem+'.json'); output=cache/(stem+'.npz')
    if receipt.exists():
        meta=json.loads(receipt.read_text())
        if not meta['complete']:
            raise SieveResourceError(dict(meta,reused_resource_receipt=True))
        with np.load(output) as saved:
            return saved['orders'],dict(meta,packing_cache_hit=True)
    try:
        orders,meta=build_ball_packing(n,radius,seconds,memory_bytes)
    except SieveResourceError as exc:
        exc.metadata['engine']=ENGINE
        receipt.write_text(json.dumps(exc.metadata,indent=2)+'\n')
        raise
    np.savez_compressed(output,orders=orders)
    meta['orders_sha256']=hashlib.sha256(orders.astype('<i2').tobytes()).hexdigest()
    receipt.write_text(json.dumps(meta,indent=2)+'\n')
    return orders,meta


def retry_sieve_order(pairs,labels,**options):
    labels=np.sort(labels); n=len(labels); k=len(pairs); J=n*(n-1)//2
    radius=n*J//k if k else J
    if k==0 or radius>=J:
        return labels,dict(path='singleton',sieve_size=1,complete=True)
    lookup={int(v):i for i,v in enumerate(labels)}
    local=np.asarray([[lookup[int(a)],lookup[int(b)]] for a,b in pairs])
    w=pair_counts(local,n)
    if radius==1:
        order,meta=even_permutation_dp(w,seconds=options.get('seconds',SECONDS),
                                      memory_bytes=options.get('memory_bytes',MEMORY))
        return labels[order],dict(meta,pairs=k)
    if radius==0:
        order,meta=lexicographic_dp(w,seconds=options.get('seconds',SECONDS),
                                  memory_bytes=options.get('memory_bytes',MEMORY))
        return labels[order],dict(meta,complete=True,sieve_size=math.factorial(n))
    orders,meta=cached_ball_packing(n,radius,**options)
    i,j=np.triu_indices(n,1); best_loss=math.inf; best=None
    for start in range(0,len(orders),32768):
        block=orders[start:start+32768]; ranks=np.argsort(block,axis=1)
        costs=(ranks[:,i]>ranks[:,j])@(w[i,j]-w[j,i])+w[j,i].sum()
        index=int(costs.argmin())
        if costs[index]<best_loss:
            best_loss=int(costs[index]);best=block[index]
    return labels[best],dict(meta,objective=best_loss,pairs=k,exact=True)


def retry_sharp_center(y,n,seed,**options):
    y=validate_rankings(y,n); N,r=y.shape
    width=math.ceil(2048*(n-1)/(r-1))
    stages=schedule(n,r,N,(r-1)/(n-1),.1)
    # All requested failures are this exact single-block branch. Do not silently
    # apply the shortcut to a different multistage Sharp construction.
    assert not stages and width>=n
    base=dict(A=256,W_star=width,padded_block_cap=8*width,depth=0,
        pilot_reports=0,actual_block_items=n,global_sieve_identical=True,
        retry_seconds=options.get('seconds',SECONDS),retry_memory=options.get('memory_bytes',MEMORY))
    pairs=extract_pairs(y,np.arange(n),np.random.default_rng(seed+173))
    try:
        order,info=retry_sieve_order(pairs,np.arange(n),**options)
    except SieveResourceError as exc:
        raise SieveResourceError(dict(exc.metadata,**base))
    return order,dict(base,branch='exact_sieve',blocks=[info],sieve_size=info['sieve_size'],
                      pairs=len(pairs),exact=True)
